#[tokio::test]
async fn a_long_running_mh_pod_releases_an_ended_meeting_and_admits_like_a_fresh_one() {
    let cluster = ClusterConnection::new()
        .await
        .expect("PRECONDITION: cluster connection (ENV_TEST_* URLs)");
    let prom = PrometheusClient::new(&cluster.prometheus_base_url);
    let handlers = handlers();

    // PRECONDITION — the AC-issued meeting-controller token, never minted here,
    // from the credentials MC itself is deployed with. A refusal names the
    // CREDENTIAL, so a rotation mismatch is not triaged as a broken forward.
    let client_id = deployment_env_value(MC_DEPLOYMENT, MC_CLIENT_ID_ENV);
    let client_secret = secret_key(MC_SECRET, MC_SECRET_KEY);
    let token = AuthClient::new(&cluster.ac_base_url)
        .issue_token(TokenRequest::client_credentials(
            &client_id,
            client_secret,
            MC_SCOPE,
        ))
        .await
        .unwrap_or_else(|e| {
            panic!(
                "PRECONDITION: AC refused MC's deployed client credentials ({client_id}, secret \
                 from {MC_SECRET}/{MC_SECRET_KEY}) — a CREDENTIAL fault: the deployed Secret and \
                 what AC was seeded with disagree. Not a forward or teardown fault. {e}"
            )
        })
        .access_token;
    let cleanup = ReleaseOnDrop {
        token: token.clone(),
        owned: Arc::new(Mutex::new(Vec::new())),
    };

    // LIMITS — both resource-guard limits are published from the value
    // enforcement reads, i.e. equal the DEPLOYED ConfigMap (never a literal here).
    let edge_limit = configmap_u64("mh-service-config", "MH_MAX_TOTAL_EGRESS_EDGES");
    let meeting_limit = configmap_u64("mh-service-config", "MH_MAX_REGISTERED_MEETINGS");
    for (metric, deployed) in [
        ("mh_media_egress_edges_limit", edge_limit),
        ("mh_media_registered_meetings_limit", meeting_limit),
    ] {
        gauge_by_instance_present(&prom, metric, handlers.len(), METRIC_BOUND).await;
        for handler in &handlers {
            #[allow(clippy::cast_precision_loss)]
            let expected = deployed as f64;
            poll_until_pinned_instance(
                &prom,
                &format!("max by (instance) ({metric})"),
                &handler.pod_ip,
                METRIC_BOUND,
                POLL_INTERVAL,
                "LIMITS",
                &format!("{expected} (the deployed ConfigMap value)"),
                |v| (v - expected).abs() < f64::EPSILON,
            )
            .await;
        }
    }

    for handler in &handlers {
        exercise_one_handler(&prom, &cleanup, &token, handler).await;
    }
}

/// The whole lifecycle on ONE pod: register, reject a foreign release, release,
/// no-op on repeat, then admit the same id afresh.
async fn exercise_one_handler(
    prom: &PrometheusClient,
    cleanup: &ReleaseOnDrop,
    token: &str,
    handler: &Handler,
) {
    let run = uuid::Uuid::new_v4().simple().to_string();
    let meeting_id = format!("env-test-teardown-{run}");
    let owner_mc = format!("env-test-mc-{run}");
    let intruder_mc = format!("env-test-intruder-{run}");
    let pinned = |promql: String,
                  phase: &'static str,
                  expectation: String,
                  pred: Box<dyn Fn(f64) -> bool + Send>| {
        let pod_ip = handler.pod_ip.clone();
        async move {
            poll_until_pinned_instance(
                prom,
                &promql,
                &pod_ip,
                METRIC_BOUND,
                POLL_INTERVAL,
                phase,
                &expectation,
                pred,
            )
            .await
        }
    };
    let name = &handler.name;
    let mut client = connect(handler).await;

    // Baselines for THIS pod. Each is also a presence control: every series here
    // is published at 0 from process start, so ABSENT is a failure, not zero.
    let any = |_: f64| true;
    let base_registered = pinned(
        REGISTERED.into(),
        "PRECONDITION",
        "presence".into(),
        Box::new(any),
    )
    .await;
    let base_edges = pinned(
        EDGES.into(),
        "PRECONDITION",
        "presence".into(),
        Box::new(any),
    )
    .await;
    let base_rejected = pinned(
        teardowns("rejected_ownership"),
        "PRECONDITION",
        "presence".into(),
        Box::new(any),
    )
    .await;
    let base_released = pinned(
        teardowns("released"),
        "PRECONDITION",
        "presence".into(),
        Box::new(any),
    )
    .await;
    let base_unknown = pinned(
        teardowns("unknown_meeting"),
        "PRECONDITION",
        "presence".into(),
        Box::new(any),
    )
    .await;

    // 1. Register (generation 1, two edges). The auth positive control: a
    //    refusal here is the token or the forward, never teardown logic.
    cleanup.record(&handler.grpc_url, &meeting_id, &owner_mc);
    let registered = client
        .register_meeting(authed(token, register(&meeting_id, &owner_mc)))
        .await
        .unwrap_or_else(|s| {
            panic!(
                "PRECONDITION: {name} refused the first RegisterMeeting ({:?}: {}) — the \
                 token or the forward, not teardown",
                s.code(),
                s.message()
            )
        })
        .into_inner();
    assert_eq!(
        registered.applied_generation, 1,
        "PRECONDITION: {name} did not install the test meeting's generation-1 policy"
    );

    // 2. CONFIRM THE RISE on this pod before anything is released — the positive
    //    control the fall is measured against.
    let peak_registered = pinned(
        REGISTERED.into(),
        "RISE-NOT-OBSERVED",
        format!(
            ">= {} (baseline {base_registered} + this meeting)",
            base_registered + 1.0
        ),
        Box::new(move |v| v >= base_registered + 1.0),
    )
    .await;
    let peak_edges = pinned(
        EDGES.into(),
        "RISE-NOT-OBSERVED",
        format!(
            ">= {} (baseline {base_edges} + two edges)",
            base_edges + TWO_EDGES
        ),
        Box::new(move |v| v >= base_edges + TWO_EDGES),
    )
    .await;

    // 3. A DIFFERENT mc_id: FAILED_PRECONDITION (never PERMISSION_DENIED, never an
    //    acknowledgement), counted, and nothing released.
    let rejected = client
        .end_meeting(authed(
            token,
            EndMeetingRequest {
                meeting_id: meeting_id.clone(),
                mc_id: intruder_mc,
            },
        ))
        .await
        .expect_err("REJECT: a mismatched mc_id must be an error status, never an acknowledgement");
    assert_eq!(
        rejected.code(),
        Code::FailedPrecondition,
        "REJECT on {name}"
    );
    assert_ne!(rejected.code(), Code::PermissionDenied, "REJECT on {name}");
    assert!(
        !rejected.message().contains(&owner_mc),
        "REJECT on {name}: the status must not disclose the registering mc_id"
    );
    pinned(
        teardowns("rejected_ownership"),
        "REJECT-COUNT",
        format!(">= {}", base_rejected + 1.0),
        Box::new(move |v| v >= base_rejected + 1.0),
    )
    .await;
    // Read AFTER the reject was scraped, so this scrape post-dates it: the
    // meeting must still be held.
    pinned(
        REGISTERED.into(),
        "REJECT-RELEASED-SOMETHING",
        format!(">= {peak_registered} (unchanged by the rejected release)"),
        Box::new(move |v| v >= peak_registered),
    )
    .await;

    // 4. The registering MC releases: acknowledged, counted, and the gauge FALLS
    //    below the peak this test observed, with the edges returned.
    let released = client
        .end_meeting(authed(
            token,
            EndMeetingRequest {
                meeting_id: meeting_id.clone(),
                mc_id: owner_mc.clone(),
            },
        ))
        .await
        .unwrap_or_else(|s| panic!("RELEASE on {name}: {:?}: {}", s.code(), s.message()))
        .into_inner();
    assert!(released.acknowledged, "RELEASE on {name}: not acknowledged");
    cleanup.forget(&meeting_id);
    pinned(
        teardowns("released"),
        "RELEASE-COUNT",
        format!(">= {}", base_released + 1.0),
        Box::new(move |v| v >= base_released + 1.0),
    )
    .await;
    pinned(
        REGISTERED.into(),
        "FALL-NOT-OBSERVED",
        format!(
            "<= {} (the observed peak {peak_registered} minus this meeting)",
            peak_registered - 1.0
        ),
        Box::new(move |v| v <= peak_registered - 1.0),
    )
    .await;
    pinned(
        EDGES.into(),
        "EDGES-NOT-RETURNED",
        format!(
            "<= {} (the observed peak {peak_edges} minus two edges)",
            peak_edges - TWO_EDGES
        ),
        Box::new(move |v| v <= peak_edges - TWO_EDGES),
    )
    .await;

    // 5. Releasing again: an acknowledged no-op, counted as unknown_meeting.
    let repeat = client
        .end_meeting(authed(
            token,
            EndMeetingRequest {
                meeting_id: meeting_id.clone(),
                mc_id: owner_mc.clone(),
            },
        ))
        .await
        .unwrap_or_else(|s| panic!("UNKNOWN on {name}: {:?}: {}", s.code(), s.message()))
        .into_inner();
    assert!(
        repeat.acknowledged,
        "UNKNOWN on {name}: a released meeting must acknowledge"
    );
    pinned(
        teardowns("unknown_meeting"),
        "UNKNOWN-COUNT",
        format!(">= {}", base_unknown + 1.0),
        Box::new(move |v| v >= base_unknown + 1.0),
    )
    .await;

    // 6. THE FRESH-POD PROOF: the same id at generation 1 installs, exactly as
    //    on a pod that never saw it. Were the generation remembered, this would
    //    be refused as stale and echo the old generation instead.
    cleanup.record(&handler.grpc_url, &meeting_id, &owner_mc);
    let again = client
        .register_meeting(authed(token, register(&meeting_id, &owner_mc)))
        .await
        .unwrap_or_else(|s| panic!("FRESH-INSTALL on {name}: {:?}: {}", s.code(), s.message()))
        .into_inner();
    assert_eq!(
        again.applied_generation, 1,
        "FRESH-INSTALL on {name}: a released meeting re-created at generation 1 must install \
         as on a fresh pod"
    );
    let done = client
        .end_meeting(authed(
            token,
            EndMeetingRequest {
                meeting_id: meeting_id.clone(),
                mc_id: owner_mc,
            },
        ))
        .await
        .unwrap_or_else(|s| panic!("CLEANUP on {name}: {:?}: {}", s.code(), s.message()))
        .into_inner();
    assert!(done.acknowledged, "CLEANUP on {name}");
    cleanup.forget(&meeting_id);
}

fn register(meeting_id: &str, mc_id: &str) -> RegisterMeetingRequest {
    RegisterMeetingRequest {
        meeting_id: meeting_id.to_string(),
        mc_id: mc_id.to_string(),
        mc_grpc_endpoint: NEVER_DIALLED_MC_ENDPOINT.to_string(),
        egress_streams: two_edges(),
        selection_rules: None,
        // Generation 1 ONLY — see "Containment" in the module docs.
        policy_generation: 1,
        server_muted_sources: Vec::new(),
    }
}
