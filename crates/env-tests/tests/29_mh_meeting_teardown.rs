//! Env-test: MH meeting teardown on the live Kind cluster (story 2 task 11;
//! R-20, R-21; ADR-0036 §8, §11).
//!
//! # What this proves that nothing else can
//!
//! That a LONG-RUNNING handler pod, after a meeting ends, admits a meeting
//! exactly as a fresh pod would — and that the operator-visible signals say so:
//! the registered-meetings gauge FALLS, the edges return, and the teardown
//! counter increments; plus the ownership-reject arm. The integration tier
//! (`crates/mh-service/tests/end_meeting_integration.rs`) proves the same
//! decisions in-process; only a live pod proves them on the deployed image, the
//! deployed ConfigMap and the real scrape path.
//!
//! # How it reaches MH
//!
//! Directly, as the meeting-controller service principal: Layer 7
//! (`scripts/layer7.sh`, step (i)) forwards each MH POD's gRPC port and exports
//! `ENV_TEST_MH_{0,1}_GRPC_URL` plus `ENV_TEST_MH_{0,1}_POD_IP`. MC does not call
//! `EndMeeting` until story 2 task 12, and a mismatched `mc_id` is unreachable
//! through MC at all (MC always sends its own), so both arms need a direct call.
//! The token comes from AC's client-credentials endpoint for the Kind dev
//! `meeting-controller` client — never minted locally — narrowed to
//! `service.write.mh`. It is used only against MH and never printed.
//! The MH client is generated by `proto-gen` (a wire-contract crate): ADR-0028's
//! layering is unchanged; only the credential convention is.
//!
//! # Containment — this test must never touch a meeting it does not own
//!
//! Every meeting id is a fresh uuid, which is the containing key (the ownership
//! state is keyed on `meeting_id`). Every registration is generation 1: a high
//! generation cannot be taken back within a process, so a large value would
//! wedge that id on that pod for the cluster's lifetime. Cleanup is STRUCTURAL —
//! a `Drop` guard releases everything this test registered, so a mid-test panic
//! cannot leak a registration (and its edges) into every later suite on the
//! cluster. `mc_grpc_endpoint` is a never-dialled placeholder: MH dials it only
//! for WebTransport clients of the meeting, and none joins a test meeting.
//!
//! # Reading metrics: pinned, relative, confirmed, no wall clock
//!
//! Metrics are read through Prometheus — the suite's one metrics path — pinned
//! to the `instance` of the pod the test CALLED (resolved by Layer 7 from the
//! same lookup that feeds the forward), never "any instance". Every expectation
//! is a DELTA from that pod's own baseline, because other suites share the pods.
//! Prometheus samples on an interval, so every read is a bounded poll until a
//! condition, never a sleep-then-assert — and the gauge FALL is asserted only
//! against a peak this test has already OBSERVED, because "below baseline" is
//! trivially true of a registration that was never scraped. Each wait fails
//! with its own phase token (PRECONDITION / RISE-NOT-OBSERVED / REJECT-COUNT /
//! RELEASE-COUNT / FALL-NOT-OBSERVED / EDGES-NOT-RETURNED / UNKNOWN-COUNT /
//! LIMITS), so a slow scrape never reads as a reclamation bug.
//!
//! What stays SYNCHRONOUS, read off the gRPC response and never re-expressed as
//! a lagged metric: the reject's status code, the acknowledgements, and
//! `applied_generation == 1` on the re-registration.

